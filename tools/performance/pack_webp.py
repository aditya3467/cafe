"""Group unchanged WebP bytes to avoid one CDN round trip per frame."""
from pathlib import Path
import json,hashlib
root=Path(__file__).resolve().parents[2];source=root/'assets/derived/hero/frames-webp-q85';dest=source/'packs';dest.mkdir(exist_ok=True)
packs=[]
for start in range(1,240,16):
 data=bytearray();frames=[]
 for n in range(start,min(start+16,240)):
  content=(source/f'frame_{n:06d}.webp').read_bytes();frames.append([n,len(data),len(content)]);data.extend(content)
 name=f'pack_{len(packs):03d}.bin';(dest/name).write_bytes(data)
 packs.append({'file':name,'bytes':len(data),'frames':frames,'sha256':hashlib.sha256(data).hexdigest()})
(dest/'manifest.json').write_text(json.dumps({'pack_size':16,'count':len(packs),'total_bytes':sum(p['bytes'] for p in packs),'packs':packs},indent=2))
module='// Generated by tools/performance/pack_webp.py; bytes are unchanged Q85 WebPs.\nconst packs='+json.dumps(packs,separators=(',',':'))+';\n'
module+="export function getFramePack(n){const index=Math.floor((n-1)/16),pack=packs[index];return pack?{...pack,index,url:new URL('../assets/derived/hero/frames-webp-q85/packs/'+pack.file,import.meta.url).href}:null;}\n"
p=root/'js/frame-sequence.js'
s=p.read_text().split('// BEGIN GENERATED PACK INDEX')[0].rstrip()
p.write_text(s+'\n\n// BEGIN GENERATED PACK INDEX\n'+module+'// END GENERATED PACK INDEX\n')
print(len(packs),'packs,',sum(p['bytes'] for p in packs),'bytes; no re-encoding.')
